def _field(
    name: str,
    type_: str,
    label: str,
    *,
    required: bool = True,
    **extra: Any,
) -> dict[str, Any]:
    doc: dict[str, Any] = {
        "name": name,
        "type": type_,
        "label": label,
        "required": required,
    }
    doc.update(extra)
    return doc


